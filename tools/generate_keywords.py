#!/usr/bin/env python3
"""Generate src/analysis/keywords.sn from sultanc-language-support metadata.

The metadata is itself synchronized from the compiler's token registry
(sultanc-language-support/tools/sync-from-compiler.sh), so keyword spellings
are never owned by the LSP.

usage: tools/generate_keywords.py path/to/syntax-surface.json [-o src/analysis/keywords.sn]
"""
import argparse, hashlib, json, pathlib

GROUPS = {"keyword", "control", "declaration", "module", "modifier", "wordOperator", "type", "literal"}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("surface")
    ap.add_argument("-o", "--output", default=str(pathlib.Path(__file__).resolve().parent.parent / "src" / "analysis" / "keywords.sn"))
    a = ap.parse_args()
    raw = pathlib.Path(a.surface).read_bytes()
    data = json.loads(raw)
    rows = []
    for k in data["keywords"]:
        if k.get("lifecycle") != "Active" or k.get("group") not in GROUPS:
            continue
        rows.append((k["english"], k["arabic"], k["group"]))
    for b in data.get("booleanLiterals", []):
        rows.append((b["english"], b["arabic"], "literal"))
    rows.sort(key=lambda r: r[0])
    q = lambda s: "«" + s + "»"
    out = [
        "// GENERATED by tools/generate_keywords.py from sultanc-language-support",
        f"// metadata/syntax-surface.json (sha256 {hashlib.sha256(raw).hexdigest()[:16]}). Do not edit.",
        "",
        "عام نوع كلمة_محجوزة_لغة = {",
        "    الإنجليزية: نص,",
        "    العربية: نص,",
        "    المجموعة: نص",
        "};",
        "",
        "عام عرف الكلمات_المحجوزة_لغة(): متجه كلمة_محجوزة_لغة {",
        "    ليكن الناتج: متغير متجه كلمة_محجوزة_لغة = [];",
    ]
    for i, (en, ar, g) in enumerate(rows):
        out.append(f"    ليكن ك{i}: كلمة_محجوزة_لغة = {{ الإنجليزية: {q(en)}, العربية: {q(ar)}, المجموعة: {q(g)} }};")
        out.append(f"    ألحق(الناتج, ك{i});")
    out += ["    أرجع الناتج;", "}", ""]
    pathlib.Path(a.output).write_text("\n".join(out), encoding="utf-8")
    print(f"{len(rows)} keywords -> {a.output}")

if __name__ == "__main__":
    main()
